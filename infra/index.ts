// apso.ai on Cloudflare. Pulumi owns everything around the site; Workers Builds (wrangler) deploys the
// site code itself, because the OpenNext bundle is built and uploaded by wrangler. See README.md.
import * as path from "path";
import * as pulumi from "@pulumi/pulumi";
import * as cloudflare from "@pulumi/cloudflare";
import * as command from "@pulumi/command";
import { records } from "./dns-records";

// Fail with one readable line instead of a provider stack trace when run outside with-secrets.sh.
const env = (name: string, item: string) => {
  const v = process.env[name];
  if (!v) throw new pulumi.RunError(`${name} is not set. Run through scripts/with-secrets.sh (1Password: ${item}). See infra/README.md.`);
  return v;
};
env("CLOUDFLARE_API_TOKEN", "op://apso-site/cloudflare-api-token/credential");

const cfg = new pulumi.Config();
const accountId = cfg.require("accountId");
const workersDevSubdomain = cfg.require("workersDevSubdomain");
const serveApex = cfg.getBoolean("serveApex") ?? false;
const DOMAIN = "apso.ai";
const WORKER = "apso-site"; // must match "name" in ../wrangler.jsonc

const zone = new cloudflare.Zone("zone", { account: { id: accountId }, name: DOMAIN, type: "full" }, { protect: true });

// Cloudflare can block AI crawlers and prepend its own disallow rules to robots.txt. Apso wants
// assistants to read and cite the site, so all three stay off.
new cloudflare.BotManagement("bots", {
  zoneId: zone.id,
  aiBotsProtection: "disabled",
  crawlerProtection: "disabled",
  isRobotsTxtManaged: false,
});

// Every non-site record from Route 53, generated by scripts/export-route53.sh. DNS only, never proxied.
records.forEach((r, i) =>
  new cloudflare.DnsRecord(`${r.type}-${r.name}-${i}`.toLowerCase(), {
    zoneId: zone.id,
    name: r.name,
    type: r.type,
    content: r.content,
    priority: r.priority,
    ttl: r.ttl,
    proxied: false,
    comment: r.purpose,
  }));

// The Worker itself, without code. Workers Builds deploys versions into it.
const worker = new cloudflare.Worker("worker", {
  accountId,
  name: WORKER,
  observability: { enabled: true },
  subdomain: { enabled: true, previewsEnabled: true },
});

// Worker secrets. The provider can only set secrets on a script it also uploads, so this calls
// wrangler's own `secret bulk`, with the values on stdin, never in a file. Re-runs when a value changes.
// NEXT_PUBLIC_* values are inlined at build time, so they are Workers Builds build variables instead.
const secrets = pulumi.secret(JSON.stringify(Object.fromEntries(
  [
    ["GHL_API_TOKEN", "op://apso-site/ghl-private-integration/token"],
    ["GHL_LOCATION_ID", "op://apso-site/ghl-private-integration/location_id"],
    ["RESEND_API_KEY", "op://apso-site/resend/credential"],
    ["CONTACT_TO_EMAIL", "deploy/secrets.env"],
  ].map(([k, item]) => [k, env(k, item)]))));
new command.local.Command("worker-secrets", {
  dir: path.resolve(__dirname, ".."),
  create: `npx --no-install wrangler secret bulk --name ${WORKER}`,
  stdin: secrets,
  triggers: [secrets],
  environment: { CLOUDFLARE_ACCOUNT_ID: accountId },
}, { dependsOn: [worker] });

// Mail authentication added after the move (Route 53 had none). Google Workspace is the only sender
// on the apex; Resend uses send.apso.ai, which carries its own SPF.
new cloudflare.DnsRecord("spf", {
  zoneId: zone.id, name: DOMAIN, type: "TXT", content: '"v=spf1 include:_spf.google.com ~all"',
  ttl: 300, comment: "SPF for Google Workspace mail",
});

// Site records copied from Route 53, so the nameserver switch changes nothing: apex still reaches
// Amplify's CloudFront, www still points where it did. Cutover only flips `proxied` and adds the
// route below, both in-place updates; a custom domain would need the apex record deleted first.
// Rollback is serveApex=false.
new cloudflare.DnsRecord("apex", {
  zoneId: zone.id, name: DOMAIN, type: "CNAME", content: "d2iezt284du3e2.cloudfront.net",
  proxied: serveApex, ttl: serveApex ? 1 : 300, comment: "Site. Amplify CloudFront until cutover",
});
new cloudflare.DnsRecord("www", {
  zoneId: zone.id, name: `www.${DOMAIN}`, type: "CNAME", content: "getapso.com",
  proxied: serveApex, ttl: serveApex ? 1 : 300, comment: "Site. Redirected to apex after cutover",
});

// Phase 3 (cutover): the Worker on the apex, and www redirecting to it.
if (serveApex) {
  new cloudflare.WorkersRoute("apex", { zoneId: zone.id, pattern: `${DOMAIN}/*`, script: WORKER }, { dependsOn: [worker] });
  new cloudflare.Ruleset("www-redirect", {
    zoneId: zone.id,
    name: "www to apex",
    kind: "zone",
    phase: "http_request_dynamic_redirect",
    rules: [{
      action: "redirect",
      expression: `(http.host eq "${DOMAIN}" and not ssl)`,
      actionParameters: {
        fromValue: {
          statusCode: 301,
          preserveQueryString: true,
          targetUrl: { expression: `concat("https://${DOMAIN}", http.request.uri.path)` },
        },
      },
    }, {
      action: "redirect",
      expression: `(http.host eq "www.${DOMAIN}")`,
      actionParameters: {
        fromValue: {
          statusCode: 301,
          preserveQueryString: true,
          targetUrl: { expression: `concat("https://${DOMAIN}", http.request.uri.path)` },
        },
      },
    }],
  });
}

export const nameServers = zone.nameServers;
export const workersDevUrl = `https://${WORKER}.${workersDevSubdomain}.workers.dev`;
export const previewPattern = `*-${WORKER}.${workersDevSubdomain}.workers.dev`; // public, per Matt 2026-10-24
