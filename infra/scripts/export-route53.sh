#!/usr/bin/env bash
# Read-only export of apso.ai's Route 53 records into infra/dns-records.ts (Pulumi declarations).
# Usage: infra/scripts/export-route53.sh   (or AWS_PROFILE=<profile> to skip the profile search)
#
# Calls only list-hosted-zones-by-name, get-hosted-zone and list-resource-record-sets.
# Skips NS and SOA (Cloudflare owns them) and the site records (A/AAAA/CNAME on apex and www), which
# index.ts replaces. Every other record, including apex MX and TXT for mail, is kept.
set -euo pipefail
ZONE=apso.ai
OUT=$(cd "$(dirname "$0")/.." && pwd)/dns-records.ts

zone_id() { AWS_PROFILE=$1 aws route53 list-hosted-zones-by-name --dns-name "$ZONE" --max-items 1 \
  --query "HostedZones[?Name=='$ZONE.'].Id | [0]" --output text 2>/dev/null; }

# The zone has lived in the "mavric" account, not the Apso ones, so all three are tried.
for p in ${AWS_PROFILE:-apso-live apso mavric}; do
  id=$(zone_id "$p") || true
  if [ -n "$id" ] && [ "$id" != None ]; then PROFILE=$p; break; fi
done
[ -n "${PROFILE:-}" ] || { echo "No Route 53 zone for $ZONE in profiles: ${AWS_PROFILE:-apso-live apso mavric}" >&2; exit 1; }

# Refuse a stale duplicate zone: its name servers must be the ones the registry delegates to.
zone_ns=$(AWS_PROFILE=$PROFILE aws route53 get-hosted-zone --id "$id" --query 'DelegationSet.NameServers' --output text | tr '\t' '\n' | sort)
live_ns=$(dig +short NS "$ZONE" | sed 's/\.$//' | sort)
[ "$zone_ns" = "$live_ns" ] || { echo "Zone $id in $PROFILE is not the delegated zone for $ZONE" >&2; exit 1; }

AWS_PROFILE=$PROFILE aws route53 list-resource-record-sets --hosted-zone-id "$id" --output json |
  ZONE=$ZONE SRC="$PROFILE $id" node -e '
const zone = process.env.ZONE;
const { ResourceRecordSets: sets, IsTruncated } = JSON.parse(require("fs").readFileSync(0, "utf8"));
if (IsTruncated) throw new Error("export truncated: add pagination");
const SKIP_TYPES = ["NS", "SOA"];
const SITE = [zone, `www.${zone}`], SITE_TYPES = ["A", "AAAA", "CNAME"];
const purpose = (name, type, value) =>
  type === "MX" && name === zone ? "Google Workspace mail for @apso.ai" :
  /google-site-verification/.test(value) ? "Google site verification" :
  /googlehosted\.com/.test(value) ? "Google domain verification CNAME" :
  name === `_dmarc.${zone}` ? "DMARC policy" :
  /_domainkey/.test(name) ? "DKIM public key (" + name.split(".")[0] + ")" :
  name === `send.${zone}` ? "Resend sending domain (bounce MX / SPF via Amazon SES)" :
  /acm-validations\.aws/.test(value) ? "ACM certificate validation for Amplify; drop after cutover" :
  /cloudfront\.net/.test(value) ? "CloudFront origin, DNS only" : "unknown: check before cutover";
const out = [], skipped = [];
for (const r of sets) {
  const name = r.Name.replace(/\.$/, "").replace(/\\052/g, "*");
  if (SKIP_TYPES.includes(r.Type) || (SITE.includes(name) && SITE_TYPES.includes(r.Type)) || r.AliasTarget || r.SetIdentifier) {
    skipped.push(`${r.Type} ${name}${r.AliasTarget ? " (alias " + r.AliasTarget.DNSName + ")" : ""}`);
    continue;
  }
  for (const { Value: v } of r.ResourceRecords) {
    const rec = { name, type: r.Type, ttl: r.TTL, purpose: purpose(name, r.Type, v) };
    if (r.Type === "MX") { const [pri, host] = v.split(/\s+/); rec.priority = Number(pri); rec.content = host.replace(/\.$/, "").toLowerCase(); }
    else rec.content = v.replace(/\.$/, "");
    out.push(rec);
  }
}
console.log(`// GENERATED by infra/scripts/export-route53.sh from Route 53 (${process.env.SRC}). Do not edit by hand.
// Skipped (Cloudflare or index.ts owns these): ${skipped.join("; ")}
export type DnsRecord = { name: string; type: string; content: string; ttl: number; priority?: number; purpose: string };
export const records: DnsRecord[] = ${JSON.stringify(out, null, 2)};`);
' > "$OUT"
echo "Wrote $(grep -c '"name"' "$OUT") records to $OUT from $PROFILE"
